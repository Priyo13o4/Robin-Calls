/** One glyph per provider. Filled brand paths where we hold a reliable one, drawn strokes for the rest. */
export function SocialGlyph({ provider, className = "size-4" }: { provider: string; className?: string }) {
  const path = FILL[provider];
  if (path) {
    return (
      <svg viewBox="0 0 24 24" aria-hidden className={className} fill="currentColor">
        <path d={path} />
      </svg>
    );
  }
  const stroke = {
    fill: "none",
    stroke: "currentColor",
    strokeWidth: 2,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
  };
  if (provider === "instagram") {
    return (
      <svg viewBox="0 0 24 24" aria-hidden className={className} {...stroke}>
        <rect x="3" y="3" width="18" height="18" rx="5" />
        <circle cx="12" cy="12" r="4" />
        <circle cx="17.2" cy="6.8" r="0.6" fill="currentColor" />
      </svg>
    );
  }
  if (provider === "youtube") {
    return (
      <svg viewBox="0 0 24 24" aria-hidden className={className} {...stroke}>
        <rect x="2.5" y="5.5" width="19" height="13" rx="4" />
        <path d="M10 9.2v5.6l4.8-2.8z" fill="currentColor" />
      </svg>
    );
  }
  if (provider === "linkedin") {
    return (
      <svg viewBox="0 0 24 24" aria-hidden className={className} {...stroke}>
        <rect x="3" y="3" width="18" height="18" rx="3" />
        <path d="M8 10.5V16M8 7.8v.1M12 16v-5.5M12 13c0-1.7 1-2.5 2.2-2.5S16 11.3 16 13v3" />
      </svg>
    );
  }
  return (
    <svg viewBox="0 0 24 24" aria-hidden className={className} {...stroke}>
      <circle cx="12" cy="12" r="9" />
      <path d="M3 12h18M12 3c3 3 3 15 0 18M12 3c-3 3-3 15 0 18" />
    </svg>
  );
}

/**
 * Icons only, never the URL. Each one links out; the destination is already
 * pinned to the platform's own host by cleanSocials, and `nofollow ugc` keeps
 * a leaderboard from passing ranking to whatever a wallet owner links.
 */
export function SocialIcons({
  socials,
  className = "",
  iconClass = "size-3.5",
}: {
  socials: Social[] | undefined;
  className?: string;
  iconClass?: string;
}) {
  const shown = (socials ?? []).slice(0, SOCIALS_MAX);
  if (shown.length === 0) return null;
  return (
    <span className={`inline-flex shrink-0 items-center gap-1.5 ${className}`}>
      {shown.map((s) => (
        <a
          key={s.provider}
          href={s.url}
          target="_blank"
          rel="noopener noreferrer nofollow ugc"
          title={providerLabel(s.provider)}
          aria-label={providerLabel(s.provider)}
          className="text-[#6f6f6f] transition-colors hover:text-[#ccff00]"
        >
          <SocialGlyph provider={s.provider} className={iconClass} />
        </a>
      ))}
    </span>
  );
}
