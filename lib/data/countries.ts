/** Get Country name and flag emoji by ISO alpha-2 code. */
export function getCountryInfo(code: string | null | undefined): CountryInfo {
  if (!code) {
    return { code: "XX", name: "Unknown / Direct", flag: "🌐" };
  }
  const upper = code.toUpperCase().trim();
  const match = COUNTRY_MAP[upper];
  if (match) {
    return { code: upper, name: match.name, flag: match.flag };
  }

  // Generic fallback with emoji conversion
  const flag =
    upper.length === 2 && /^[A-Z]{2}$/.test(upper)
      ? String.fromCodePoint(...[...upper].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65))
      : "🌐";

  return { code: upper, name: upper, flag };
}
