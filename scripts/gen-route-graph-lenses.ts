// Regenerate the lens constants after editing contracts/src/route-graph/*.sol:
//   (cd contracts && forge build --contracts src/route-graph) && npx tsx scripts/gen-route-graph-lenses.ts
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const LENSES = [
  { contract: "PoolDepthLens", fn: "measure", out: "lib/swap/pool-depth-lens.ts", prefix: "POOL_DEPTH_LENS" },
  { contract: "RouteQuoteLens", fn: "quote", out: "lib/swap/route-quote-lens.ts", prefix: "ROUTE_QUOTE_LENS" },
];

for (const l of LENSES) {
  const src = `contracts/src/route-graph/${l.contract}.sol`;
  const art = JSON.parse(readFileSync(`contracts/out/${l.contract}.sol/${l.contract}.json`, "utf8"));
  const sha = createHash("sha256").update(readFileSync(src)).digest("hex");
  const abi = art.abi.filter((x: { name?: string }) => x.name === l.fn);
  writeFileSync(l.out, `// GENERATED by scripts/gen-route-graph-lenses.ts from ${src}. Do not edit.
// Runs only as eth_call state-override code; never deployed.
export const ${l.prefix}_SOURCE_SHA256 = "${sha}";
export const ${l.prefix}_ABI = ${JSON.stringify(abi)} as const;
export const ${l.prefix}_CODE = "${art.deployedBytecode.object}" as const;
`);
  console.log(`wrote ${l.out} ${sha.slice(0, 12)}`);
}
